async function seed() {
  console.log(`Starting to seed ${dummyStudents.length} dummy students...`);
  const year = new Date().getFullYear();
  const batch = db.batch();

  for (let i = 0; i < dummyStudents.length; i++) {
    const s = dummyStudents[i];
    const docRef = db.collection("participants").doc();
    const levelCode =
      { district: "DT", state: "ST", "south-india": "SI", national: "NT" }[s.level] || "DT";
    const serialNumber = `${year}-${levelCode}-${docRef.id.slice(-8).toUpperCase()}`;

    batch.set(docRef, {
      ...s,
      serialNumber,
      paidAt: admin.firestore.FieldValue.serverTimestamp(),
      createdAt: admin.firestore.FieldValue.serverTimestamp(),
      razorpayPaymentId: `pay_demo_${docRef.id.slice(0, 10)}`,
    });
  }

  await batch.commit();
  console.log(`Successfully added ${dummyStudents.length} dummy students to Firestore!`);
}

seed()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("Seeding failed:", err);
    process.exit(1);
  });

